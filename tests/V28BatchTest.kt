import com.abhi.ganasuno.data.Batch28
import java.time.LocalDate

fun main(){
    var count=0
    fun verify(ok:Boolean){check(ok);count++}
    val rows=Batch28.parse("320 https://example.org/high.mp3\n128 https://example.org/low.mp3\n256 https://example.org/mid.mp3")
    verify(rows.map{it.kbps}==listOf(128,256,320))
    verify(Batch28.select(rows,320)?.kbps==320)
    verify(Batch28.select(rows,192)?.kbps==128)
    verify(Batch28.select(rows,250)?.kbps==256)
    verify(Batch28.select(emptyList(),128)==null)
    verify(Batch28.direct("http://example.org/song.mp3")==null)
    verify(Batch28.direct("https://music.youtube.com/a")==null)
    verify(Batch28.direct("https://x.googlevideo.com/a")==null)
    verify(Batch28.direct("https://a.spotify.com/a")==null)
    verify(Batch28.direct("https://user:secret@example.org/a")==null)
    verify(Batch28.direct("https://example.org:8080/a")==null)
    verify(Batch28.direct("https://localhost/a")==null)
    verify(Batch28.direct("https://127.0.0.1/a")==null)
    verify(Batch28.direct("https://example.org/a#part")==null)
    verify(runCatching{Batch28.parse("128 https://example.org/a\n128 https://example.org/b")}.isFailure)
    verify(runCatching{Batch28.parse("0 https://example.org/a")}.isFailure)
    verify(Batch28.candidates(listOf("a","b"),listOf("c","a","d"),setOf("a","b","c","d"),setOf("b"),true,true,3)==listOf("a","c","d"))
    verify(Batch28.candidates(listOf("a"),listOf("b"),setOf("b"),emptySet(),true,false,5).isEmpty())
    verify(Batch28.candidates(listOf("a"),listOf("b"),setOf("a","b"),emptySet(),false,true,5)==listOf("b"))
    verify(Batch28.candidates(listOf("a"),listOf("b"),setOf("a","b"),emptySet(),false,false,5).isEmpty())
    verify(Batch28.candidates(listOf("a","b"),emptyList(),setOf("a","b"),emptySet(),true,false,1)==listOf("a"))
    val today=LocalDate.parse("2026-11-25");val a=Batch28.Release("12345678-1234-1234-1234-123456789abc","A","2026-11-24");val b=Batch28.Release("12345678-1234-1234-1234-123456789abd","B","2026-09-01")
    verify(Batch28.unseen(listOf(a,b),emptySet(),false,today).isEmpty())
    verify(Batch28.unseen(listOf(a,a,b),emptySet(),true,today)==listOf(a))
    verify(Batch28.unseen(listOf(a),setOf(a.id),true,today).isEmpty())
    verify(Batch28.unseen(listOf(a.copy(date="2027-01-01")),emptySet(),true,today).isEmpty())
    val fp="ab".repeat(32);verify(Batch28.fingerprints(fp.uppercase().chunked(2).joinToString(":"))==setOf(fp))
    verify(Batch28.fingerprints("invalid").isEmpty())
    verify(Batch28.signatureStatus(setOf(fp),setOf(fp)).startsWith("Matches"))
    verify(Batch28.signatureStatus(setOf(fp),emptySet()).startsWith("Unconfigured"))
    verify(Batch28.signatureStatus(setOf(fp),setOf("cd".repeat(32))).contains("mismatch"))
    verify(!Batch28.scrobbleEligible(30000,30000))
    verify(!Batch28.scrobbleEligible(180000,89999))
    verify(Batch28.scrobbleEligible(180000,90000))
    verify(Batch28.scrobbleEligible(600000,240000))
    verify(!Batch28.scrobbleEligible(600000,239999))
    verify(Batch28.lastFmSignature(mapOf("sk" to "b","method" to "track.scrobble","api_key" to "a","format" to "json"),"secret")=="e599a6f6f221cadfb1f366944562a6a0")
    println("V28: $count assertions passed")
}
