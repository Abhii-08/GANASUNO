import com.abhi.ganasuno.data.*
fun main(){
 var n=0
 fun verify(v:Boolean){check(v){"Assertion ${n+1} failed"};n++}
 val id="UC"+"a".repeat(22)
 verify(Batch22.channel(id)==id)
 verify(Batch22.channel("https://www.youtube.com/channel/$id")==id)
 verify(Batch22.channel("https://evil.example/channel/$id")==null)
 verify(Batch22.channel("https://user@youtube.com/channel/$id")==null)
 verify(Batch22.httpsFile("https://example.com/a.gif?x=y")!=null)
 verify(Batch22.httpsFile("http://example.com/a.gif")==null)
 verify(Batch22.httpsFile("https://u:p@example.com/a.gif")==null)
 verify(Batch22.httpsFile("https://example.com:8080/a.gif")==null)
 verify(Batch22.token("a".repeat(25)))
 verify(!Batch22.token("a".repeat(25)+"\n"))
 verify(!Batch22.token("short"))
 verify(Batch22.duration("3:20")==200000L)
 verify(Batch22.duration("1:02:03")==3723000L)
 verify(Batch22.duration("3:60")==null)
 val seed=Song("aaaaaaaaaaa","Song","Artist","3:20","")
 val matching=seed.copy(id="bbbbbbbbbbb",title="Song (Live)",duration="3:24")
 val long=seed.copy(id="ccccccccccc",title="Song (Remix)",duration="5:24")
 verify(Batch22.versions(seed,listOf(seed,long,matching,matching,matching.copy(id="ddddddddddd",artist="Other")))==listOf(matching,long))
 verify(Batch22.versionScore(seed,matching.copy(title="Different"))==null)
 verify(Batch22.versionScore(seed,matching.copy(live=true))==null)
 verify(Batch22.nextOffset(0,20,45)==20)
 verify(Batch22.nextOffset(40,20,45)==null)
 verify(Batch22.nextOffset(10000,20,20000)==null)
 verify(Batch22.checkedSize(100,100,200))
 verify(!Batch22.checkedSize(99,100,200))
 verify(!Batch22.checkedSize(0,-1,200))
 verify(!Batch22.checkedSize(201,-1,200))
 verify(Batch22.checkedSize(99,-1,200))
 verify(Batch22.seek(.99f,.05f)==1f)
 verify(Batch22.seek(.01f,-.05f)==0f)
 verify(Batch22.seek(Float.NaN,.05f)==0f)
 verify(Batch22.sync(1000,2000,1.0,true,false).speed>1f)
 verify(Batch22.sync(2000,1000,1.0,true,false).speed<1f)
 verify(Batch22.sync(1000,4000,1.0,true,false).seek)
 verify(!Batch22.sync(1000,4000,1.0,true,true).seek)
 verify(Batch22.sync(1000,1400,1.0,false,false).seek)
 verify(Batch22.sync(1000,1100,1.0,true,false).speed==1f)
 verify(Batch22.sync(1000,2000,2.0,true,false).speed==2f)
 verify(Batch22.sync(2000,1000,.5,true,false).speed==.5f)
 verify(Batch22.count("12345678901234567890")=="12345678901234567890")
 verify(Batch22.count("-1")=="Unavailable")
 verify(Batch22.bpmAlternatives(120)==listOf(120,60,240))
 verify(Batch22.bpmAlternatives(200)==listOf(200,100))
 verify(Batch22.bpmAlternatives(null).isEmpty())
 println("$n v22 assertions passed")
}
